CREATE TABLE cd_email_queue (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    entity_type VARCHAR(255) NULL,
    entity_id VARCHAR(255) NULL,
    recipient_encrypted TEXT NOT NULL,
    recipient_iv VARCHAR(255) NOT NULL,
    recipient_tag VARCHAR(255) NOT NULL,
    recipient_key_id VARCHAR(255) NOT NULL,
    payload_encrypted TEXT NOT NULL,
    payload_iv VARCHAR(255) NOT NULL,
    payload_tag VARCHAR(255) NOT NULL,
    payload_key_id VARCHAR(255) NOT NULL,
    template_key VARCHAR(255) NOT NULL,
    language VARCHAR(255) NOT NULL,
    sender_type INTEGER NOT NULL,
    priority INTEGER NOT NULL DEFAULT 5,
    status VARCHAR(50) NOT NULL DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error TEXT NULL,
    retry_after DATETIME NULL,
    sent_at DATETIME NULL,
    scheduled_at DATETIME NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL
);
